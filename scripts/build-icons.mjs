// Bundles Fluent Emoji (flat, MIT, Microsoft) SVGs for every emoji the app's source uses (I1).
// Scans src/ (not tests) for emoji, maps each to its Fluent icon name, writes public/icons/<name>.svg
// and src/icons/iconMap.gen.ts. Run `npm run icons` after adding emoji; a test fails if it's stale.
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { scanEmoji, emojiKey } from './emojiScan.mjs';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const pkg = path.join(root, 'node_modules/@iconify-json/fluent-emoji-flat');
const icons = JSON.parse(fs.readFileSync(path.join(pkg, 'icons.json'), 'utf8'));
const chars = JSON.parse(fs.readFileSync(path.join(pkg, 'chars.json'), 'utf8'));

function resolveBody(name) {
  if (icons.icons[name]) return icons.icons[name];
  const alias = icons.aliases?.[name];
  return alias ? resolveBody(alias.parent) : undefined;
}

export function buildIconMap(emojiList) {
  const map = {}; // emoji key (no FE0F) -> icon name
  const missing = [];
  for (const e of emojiList) {
    const k = emojiKey(e);
    const hex = [...k].map((c) => c.codePointAt(0).toString(16)).join('-');
    const name = chars[hex];
    if (name && resolveBody(name)) map[k] = name;
    else missing.push(e);
  }
  return { map, missing };
}

export function renderMapModule(map, missing) {
  const keys = Object.keys(map).sort();
  const lines = keys.map((k) => `  ${JSON.stringify(k)}: ${JSON.stringify(map[k])},`);
  return `// GENERATED by scripts/build-icons.mjs — do not edit. Run \`npm run icons\` to refresh.
// Emoji (without U+FE0F) -> Fluent Emoji Flat icon name; the SVG is public/icons/<name>.svg.
export const EMOJI_ICON: Record<string, string> = {
${lines.join('\n')}
};

// Emoji used in the app with no Fluent icon: they render as system emoji.
export const NO_ICON: string[] = ${JSON.stringify(missing.sort())};
`;
}

if (process.argv[1] && fileURLToPath(import.meta.url) === path.resolve(process.argv[1])) {
  const used = scanEmoji(path.join(root, 'src'));
  const { map, missing } = buildIconMap([...used.keys()]);
  const outDir = path.join(root, 'public/icons');
  fs.rmSync(outDir, { recursive: true, force: true });
  fs.mkdirSync(outDir, { recursive: true });
  let bytes = 0;
  for (const name of new Set(Object.values(map))) {
    const ic = resolveBody(name);
    const w = ic.width ?? icons.width ?? 32;
    const h = ic.height ?? icons.height ?? 32;
    const svg = `<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 ${w} ${h}">${ic.body}</svg>\n`;
    fs.writeFileSync(path.join(outDir, `${name}.svg`), svg);
    bytes += svg.length;
  }
  fs.writeFileSync(path.join(root, 'src/icons/iconMap.gen.ts'), renderMapModule(map, missing));
  console.log(`icons: ${new Set(Object.values(map)).size} SVGs (${(bytes / 1024).toFixed(0)} KB), no icon for: ${missing.join(' ') || 'none'}`);
}
